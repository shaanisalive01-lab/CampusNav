test("a real stacked-header timetable gives all 30 classes", () => {
    const got = {};
    parseTimetable(WORDS).forEach(c => {
        (got[c.day] = got[c.day] || []).push([c.startTime, c.endTime, c.subject, c.room].join(" "));
    });
    assert.deepStrictEqual(got, EXPECTED);
});

test("a stacked header with no day rows gives nothing instead of guessing", () => {
    assert.deepStrictEqual(parseTimetable(WORDS.filter(w => !/day$/i.test(w.text))), []);
});

test("two readings are combined without doubling words", () => {
    const word = (text, x, c) => ({ text, c, x0: x, y0: 0, x1: x + 40, y1: 20 });
    const merged = mergeWords([word("PLC", 0, 90), word("a1", 100, 30)], [word("PLC", 2, 92), word("LG", 101, 95), word("LAB", 200, 80)]);
    assert.deepStrictEqual(merged.map(w => w.text), ["PLC", "LG", "LAB"]);
});
